# -*- coding: utf-8 -*-
"""Generate migration 021 and src/lib/demoParcoursFiches.ts from parcours_fiches_data.py."""
import json, os, re, sys
sys.path.insert(0, os.path.dirname(__file__))
from parcours_fiches_data import FICHES, EXISTING_LINKS

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FORBIDDEN = re.compile(r'(mot de passe|password|rituel|\+41|\b0\d{2} ?\d{3})', re.I)

def q(s):
    return "'" + s.replace("'", "''") + "'"

def steps_json(steps):
    return json.dumps([{'order': i + 1, 'text': t} for i, t in enumerate(steps)], ensure_ascii=False)

for f in FICHES:
    blob = f['title'] + f['summary'] + ''.join(f['steps'])
    if FORBIDDEN.search(blob):
        sys.exit('Forbidden content in ' + f['slug'])

sql = ["-- Step fiches for all parcours (Julien, 2026-11-03). Generated by scripts/gen_parcours_fiches.py.",
       "-- Sources: documents jeux (CDC VR, CDC EL, Manuel Couvent, Script DVC, Vinum, Processus/Tableaux Sierre).",
       "-- No passwords, codes or phone numbers. Mirrors existing convention: is_required = true.", ""]
for f in FICHES:
    kind, slugs = f['scope']
    sql.append(f"-- {f['slug']}")
    sql.append(
        "INSERT INTO public.procedure_fiches (category, title, summary, content_steps, is_placeholder, tags, is_active, is_required, scope_kind, sort_order)\n"
        f"SELECT {q(f['category'])}, {q(f['title'])}, {q(f['summary'])}, {q(steps_json(f['steps']))}::jsonb, "
        f"{'true' if f['placeholder'] else 'false'}, ARRAY[{', '.join(q(t) for t in f['tags'])}], true, true, {q(kind)},\n"
        f"  COALESCE((SELECT max(sort_order) FROM public.procedure_fiches WHERE category = {q(f['category'])} AND deleted_at IS NULL), 0) + 10\n"
        f"WHERE NOT EXISTS (SELECT 1 FROM public.procedure_fiches WHERE title = {q(f['title'])} AND deleted_at IS NULL);")
    table, col, ref = ('fiche_scope_locations', 'location_id', 'locations') if kind == 'locations' else ('fiche_scope_games', 'game_id', 'games')
    sql.append(
        f"INSERT INTO public.{table} (fiche_id, {col})\n"
        f"SELECT f.id, r.id FROM public.procedure_fiches f JOIN public.{ref} r ON r.slug IN ({', '.join(q(s) for s in slugs)})\n"
        f"WHERE f.title = {q(f['title'])} AND f.deleted_at IS NULL\nON CONFLICT DO NOTHING;")
    sql.append("")

def link_sql(title, links):
    values = ', '.join(f"({q(p)}, {q(k)})" for p, k in links)
    return (f"INSERT INTO public.session_step_fiches (parcours_id, step, fiche_id)\n"
            f"SELECT v.p, v.k, f.id FROM public.procedure_fiches f CROSS JOIN (VALUES {values}) AS v(p, k)\n"
            f"WHERE f.title = {q(title)} AND f.deleted_at IS NULL\nON CONFLICT DO NOTHING;")

sql.append("-- Links: new fiches")
for f in FICHES:
    sql.append(link_sql(f['title'], f['links']))
sql.append("\n-- Links: existing fiches reused")
for title, _demo, links in EXISTING_LINKS:
    sql.append(link_sql(title, links))
open(os.path.join(ROOT, 'supabase/migrations/021_parcours_step_fiches_content.sql'), 'w').write('\n'.join(sql) + '\n')

# ---- demo TS
ts = ["// Generated by scripts/gen_parcours_fiches.py — do not edit by hand.",
      "import { ProcedureFiche } from './database.types';",
      "import { mockStepFichesMapping } from './mockData';", "",
      "const NOW = '2026-11-03T12:00:00.000Z';", "",
      "function fiche(id: string, category: ProcedureFiche['category'], title: string, summary: string, isPlaceholder: boolean,",
      "  scopeKind: 'locations' | 'games', scopeIds: string[], steps: string[]): ProcedureFiche {",
      "  return {",
      "    id, category, title, summary,",
      "    content_steps: steps.map((text, index) => ({ order: index + 1, text })),",
      "    is_placeholder: isPlaceholder, tags: [], is_active: true, is_required: true, version: 1, deleted_at: null,",
      "    scope_kind: scopeKind,",
      "    scope_location_ids: scopeKind === 'locations' ? scopeIds.map((slug) => `loc-${slug}`) : [],",
      "    scope_game_ids: scopeKind === 'games' ? scopeIds.map((slug) => `game-${slug}`) : [],",
      "    created_at: NOW, updated_at: NOW,",
      "  };", "}", "",
      "/** Demo copies of the step fiches of migration 021 (+ the VR pitch fiche). */",
      "export const DEMO_PARCOURS_FICHES: ProcedureFiche[] = ["]
ts.append("  fiche('demo-pitch', 'procedure_deroulement', 'Pitch du studio et des jeux', 'Comment présenter le Virtual Reality Center et les jeux aux clients', false, 'locations', ['vr_center'], "
          + json.dumps(["Demander aux clients s'ils ont déjà fait de la VR.", "Tout est fait maison à Sion : recherche historique, 3D, voix d'acteurs valaisans.", "2 halles de 160 m² en free roam multijoueur.", "Innovations techniques : zéro désagrément, zéro nausée ; interaction et coopération.", "Sion au XVe siècle et scénario du jeu : adapter le pitch au jeu choisi et au groupe."], ensure_ascii=False) + "),")
for f in FICHES:
    kind, slugs = f['scope']
    ts.append(f"  fiche({json.dumps('demo-' + f['slug'])}, {json.dumps(f['category'])}, {json.dumps(f['title'], ensure_ascii=False)}, "
              f"{json.dumps(f['summary'], ensure_ascii=False)}, {'true' if f['placeholder'] else 'false'}, {json.dumps(kind)}, {json.dumps(slugs)}, "
              f"{json.dumps(f['steps'], ensure_ascii=False)}),")
ts.append("];\n")
links = {}
for f in FICHES:
    for p, k in f['links']:
        links.setdefault(f"{p}:{k}", []).append('demo-' + f['slug'])
for _t, demo_id, ls in EXISTING_LINKS:
    for p, k in ls:
        links.setdefault(f"{p}:{k}", []).append(demo_id)
ts.append("/** Demo step → fiche links, keyed `${parcoursId}:${stepKey}`. VR legacy keys come from mockStepFichesMapping. */")
ts.append("export const DEMO_STEP_FICHE_LINKS: Record<string, string[]> = {")
ts.append("  ...Object.fromEntries(Object.entries(mockStepFichesMapping).map(([key, ids]) => [`vr_centre_client:${key}`, ids || []])),")
for k, v in links.items():
    ts.append(f"  {json.dumps(k)}: {json.dumps(v)},")
ts.append("};")
open(os.path.join(ROOT, 'src/lib/demoParcoursFiches.ts'), 'w').write('\n'.join(ts) + '\n')
print('ok', len(FICHES), 'fiches,', len(links), 'demo link keys')
